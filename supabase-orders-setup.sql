-- MAINSTREAM demo order storage
-- Run once in Supabase Dashboard > SQL Editor.
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  customer_name text not null default 'Guest Customer',
  items jsonb not null default '[]'::jsonb,
  total numeric(12,2) not null default 0 check (total >= 0),
  payment_method text,
  payment_status text not null default 'unpaid_demo',
  order_status text not null default 'pending_payment',
  created_at timestamptz not null default now()
);

-- Delivery and payment identifiers used by checkout and the admin orders page.
alter table public.orders
  add column if not exists customer_email text,
  add column if not exists customer_phone text,
  add column if not exists shipping_address text,
  add column if not exists shipping_city text,
  add column if not exists shipping_pincode text,
  add column if not exists shipping_state text,
  add column if not exists razorpay_order_id text,
  add column if not exists razorpay_payment_id text,
  add column if not exists paid_at timestamptz;

alter table public.orders enable row level security;

drop policy if exists "Public can create unpaid demo orders" on public.orders;
create policy "Public can create unpaid demo orders"
on public.orders for insert
to anon, authenticated
with check (
  payment_status = 'unpaid_demo'
  and order_status = 'pending_payment'
  and total >= 0
);

drop policy if exists "Authenticated admins can read orders" on public.orders;
create policy "Authenticated admins can read orders"
on public.orders for select
to authenticated
using (auth.uid() is not null);

drop policy if exists "Authenticated admins can delete orders" on public.orders;
create policy "Authenticated admins can delete orders"
on public.orders for delete
to authenticated
using (auth.uid() is not null);

grant insert on public.orders to anon, authenticated;
grant select, delete on public.orders to authenticated;

create index if not exists orders_created_at_idx
on public.orders (created_at desc);


-- MAINSTREAM admin settings
create table if not exists public.store_settings (
  id integer primary key default 1 check (id = 1),
  store_name text not null default 'MAINSTREAM',
  contact_email text,
  contact_phone text,
  shipping_charge numeric(10,2) not null default 0,
  free_shipping_threshold numeric(10,2),
  updated_at timestamptz not null default now()
);
insert into public.store_settings (id) values (1) on conflict (id) do nothing;
alter table public.store_settings enable row level security;
drop policy if exists "Authenticated admins can read store settings" on public.store_settings;
create policy "Authenticated admins can read store settings" on public.store_settings for select to authenticated using (auth.uid() is not null);
drop policy if exists "Authenticated admins can update store settings" on public.store_settings;
create policy "Authenticated admins can update store settings" on public.store_settings for update to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
grant select, update on public.store_settings to authenticated;

-- Wishlist events are associated with an anonymous browser ID until customer accounts are introduced.
create table if not exists public.wishlist_items (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  product_slug text not null,
  product_name text,
  product_image text,
  created_at timestamptz not null default now(),
  unique(visitor_id, product_slug)
);
alter table public.wishlist_items enable row level security;
drop policy if exists "Visitors can add wishlist items" on public.wishlist_items;
create policy "Visitors can add wishlist items" on public.wishlist_items for insert to anon, authenticated with check (length(visitor_id) between 8 and 100);
drop policy if exists "Visitors can remove own wishlist items" on public.wishlist_items;
create policy "Visitors can remove own wishlist items" on public.wishlist_items for delete to anon, authenticated using (length(visitor_id) between 8 and 100);
drop policy if exists "Authenticated admins can view wishlist items" on public.wishlist_items;
create policy "Authenticated admins can view wishlist items" on public.wishlist_items for select to authenticated using (auth.uid() is not null);
grant insert, delete on public.wishlist_items to anon, authenticated;
grant select on public.wishlist_items to authenticated;
